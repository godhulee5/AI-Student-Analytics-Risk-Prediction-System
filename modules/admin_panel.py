import streamlit as st
import pandas as pd

from utils.data_manager import load_students, save_students


# ============================================================
# REQUIRED STUDENT DATASET COLUMNS
# ============================================================

REQUIRED_COLUMNS = [
    "Student_ID",
    "Gender",
    "Age",
    "Major",
    "Attendance_Pct",
    "Study_Hours_Per_Day",
    "Previous_CGPA",
    "Sleep_Hours",
    "Social_Hours_Week",
    "Final_CGPA",
    "Grade",
    "Risk_Level"
]


def render(data_dir, model_dir):

    st.markdown(
        """
        <div class="hero">
            <h1>Admin Panel</h1>
            <p>
                System controls, data refresh and application status.
            </p>
        </div>
        """,
        unsafe_allow_html=True
    )

    df = load_students(data_dir)

    # ========================================================
    # SYSTEM STATUS
    # ========================================================

    st.subheader("System Status")

    c1, c2, c3 = st.columns(3)

    c1.metric(
        "Student Records",
        len(df)
    )

    c2.metric(
        "Dataset",
        "Connected"
        if (data_dir / "student_data_cleaned.csv").exists()
        else "Missing"
    )

    c3.metric(
        "AI Models",
        "Ready"
        if (
            (model_dir / "grade_model.pkl").exists()
            and
            (model_dir / "risk_model.pkl").exists()
        )
        else "Not Ready"
    )

    # ========================================================
    # DATA MANAGEMENT
    # ========================================================

    st.subheader("Data Management")

    uploaded = st.file_uploader(
        "Upload Student Dataset",
        type=["csv"],
        help=(
            "Upload ONLY the cleaned student dataset generated "
            "from the project's Colab notebook."
        )
    )

    if uploaded is not None:

        try:

            new_df = pd.read_csv(uploaded)

            # ------------------------------------------------
            # VALIDATE COLUMNS BEFORE REPLACING DATASET
            # ------------------------------------------------

            missing_columns = [
                column
                for column in REQUIRED_COLUMNS
                if column not in new_df.columns
            ]

            if missing_columns:

                st.error(
                    "❌ Upload rejected. The CSV does not match "
                    "the StudentIQ dataset structure."
                )

                st.write("Missing columns:")

                st.code(
                    "\n".join(missing_columns)
                )

                st.info(
                    "Please upload the student_data_cleaned.csv "
                    "generated by the project's Google Colab notebook."
                )

            else:

                # --------------------------------------------
                # VALID DATASET
                # --------------------------------------------

                save_students(
                    new_df,
                    data_dir
                )

                # Remove old models
                for p in model_dir.glob("*.pkl"):
                    p.unlink()

                metrics = (
                    model_dir /
                    "model_metrics.json"
                )

                if metrics.exists():
                    metrics.unlink()

                st.success(
                    "✅ Student dataset uploaded successfully. "
                    "Old AI models were cleared and will be rebuilt."
                )

                st.rerun()

        except Exception as e:

            st.error(
                f"Could not import the dataset: {e}"
            )

    # ========================================================
    # DATASET STRUCTURE
    # ========================================================

    st.subheader("Current Dataset Structure")

    st.write(
        f"Current student records: **{len(df):,}**"
    )

    st.write(
        f"Current columns: **{len(df.columns)}**"
    )

    missing_current = [
        column
        for column in REQUIRED_COLUMNS
        if column not in df.columns
    ]

    if missing_current:

        st.error(
            "Current dataset is missing required columns:"
        )

        st.code(
            "\n".join(missing_current)
        )

    else:

        st.success(
            "✅ Current dataset structure is valid."
        )

    # ========================================================
    # ADMIN INFORMATION
    # ========================================================

    st.subheader("Administration")

    st.info(
        "This application is restricted to college administrators. "
        "Administrators can manage student data and refresh the AI "
        "models when a valid student dataset is uploaded."
    )

    st.warning(
        "For real deployment, change the demo administrator "
        "credentials in utils/auth.py and use secure authentication."
    )